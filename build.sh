#!/bin/bash
# Builds Blur Wallpaper Maker into a runnable .app bundle (no Xcode required).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
APP="$ROOT/build/Blur Wallpaper Maker.app"
BIN_DIR="$APP/Contents/MacOS"
BIN="$BIN_DIR/BlurWallpaperMaker"

SDK="$(xcrun --sdk macosx --show-sdk-path)"
ARCH="$(uname -m)"   # arm64 on Apple Silicon, x86_64 on Intel

echo "▸ Cleaning previous build"
rm -rf "$APP"
mkdir -p "$BIN_DIR" "$APP/Contents/Resources"

echo "▸ Generating secrets from .env"
UNSPLASH_ACCESS_KEY=""
if [ -f "$ROOT/.env" ]; then
  set -a; . "$ROOT/.env"; set +a
else
  echo "  (no .env found — building without a bundled Unsplash key)"
fi
GEN="$ROOT/build/Secrets.generated.swift"
cat > "$GEN" <<EOF
// AUTO-GENERATED by build.sh from .env — do not edit or commit.
enum Secrets {
    static let unsplashKey = "${UNSPLASH_ACCESS_KEY:-}"
}
EOF

echo "▸ Compiling ($ARCH)"
swiftc -O -parse-as-library \
  -sdk "$SDK" \
  -target "${ARCH}-apple-macos14.0" \
  -o "$BIN" \
  "$ROOT"/Sources/*.swift \
  "$GEN"

echo "▸ Assembling bundle"
cp "$ROOT/Info.plist" "$APP/Contents/Info.plist"

echo "▸ Ad-hoc code signing"
codesign --force --sign - "$APP" >/dev/null 2>&1 || echo "  (codesign skipped)"

echo "✓ Built: $APP"
echo "  Run with:  open \"$APP\""
