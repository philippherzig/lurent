#!/bin/bash
# Builds Lurent into a runnable .app bundle (no Xcode required).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
APP="$ROOT/build/Lurent.app"
BIN_DIR="$APP/Contents/MacOS"
BIN="$BIN_DIR/Lurent"

SDK="$(xcrun --sdk macosx --show-sdk-path)"
ARCH="$(uname -m)"   # arm64 on Apple Silicon, x86_64 on Intel

echo "▸ Cleaning previous build"
rm -rf "$APP"
mkdir -p "$BIN_DIR" "$APP/Contents/Resources"

echo "▸ Generating secrets from .env"
UNSPLASH_ACCESS_KEY=""
if [ -f "$ROOT/.env" ]; then
  set -a; . "$ROOT/.env"; set +a
else
  echo "  (no .env found — building without a bundled Unsplash key)"
fi
GEN="$ROOT/build/Secrets.generated.swift"
cat > "$GEN" <<EOF
// AUTO-GENERATED by build.sh from .env — do not edit or commit.
enum Secrets {
    static let unsplashKey = "${UNSPLASH_ACCESS_KEY:-}"
}
EOF

# PROVISION_PROFILE switches the whole build to the App Store variant: sandboxed,
# provisioned, and **without Sparkle** — the Store forbids apps that update
# themselves, so the framework is neither linked nor embedded and Updater.swift
# compiles to a stub. Unset, everything below behaves exactly as before.
PROVISION_PROFILE="${PROVISION_PROFILE-}"
if [ -n "$PROVISION_PROFILE" ]; then
  [ -f "$PROVISION_PROFILE" ] || { echo "  ✗ profile not found: $PROVISION_PROFILE"; exit 1; }
  APP_STORE_BUILD=1
else
  APP_STORE_BUILD=0
fi

SWIFT_FLAGS=()
if [ "$APP_STORE_BUILD" = 1 ]; then
  echo "▸ App Store variant — skipping Sparkle"
  SWIFT_FLAGS+=(-D APP_STORE)
else
  echo "▸ Ensuring Sparkle is vendored"
  "$ROOT/Tools/fetch-sparkle.sh"
  # -F/-framework let swiftc find the Sparkle module + link it; the rpath tells the
  # built binary to load Sparkle.framework from Contents/Frameworks at runtime.
  SWIFT_FLAGS+=(-F "$ROOT/vendor/Sparkle" -framework Sparkle
                -Xlinker -rpath -Xlinker "@executable_path/../Frameworks")
fi

echo "▸ Compiling ($ARCH)"
swiftc -O -parse-as-library \
  -sdk "$SDK" \
  -target "${ARCH}-apple-macos26.0" \
  "${SWIFT_FLAGS[@]}" \
  -o "$BIN" \
  "$ROOT"/Sources/*.swift \
  "$GEN"

echo "▸ Assembling bundle"
cp "$ROOT/Info.plist" "$APP/Contents/Info.plist"
if [ "$APP_STORE_BUILD" = 1 ]; then
  # Sparkle's feed keys would advertise a self-update mechanism that isn't there.
  for k in SUFeedURL SUPublicEDKey SUEnableAutomaticChecks; do
    plutil -remove "$k" "$APP/Contents/Info.plist" >/dev/null 2>&1 || true
  done
  echo "  (removed the Sparkle keys)"
fi

echo "▸ Copying localizations"
# Each Localizations/<lang>.lproj/Localizable.strings ships as a bundle
# localization; German is the base (the string literals in code are the keys).
if compgen -G "$ROOT/Localizations/*.lproj" >/dev/null; then
  cp -R "$ROOT/Localizations/"*.lproj "$APP/Contents/Resources/"
  echo "  ($(ls -d "$ROOT/Localizations/"*.lproj | wc -l | tr -d ' ') localizations)"
fi

SPARKLE_FW=""
if [ "$APP_STORE_BUILD" = 0 ]; then
  echo "▸ Embedding Sparkle.framework"
  FRAMEWORKS="$APP/Contents/Frameworks"
  SPARKLE_FW="$FRAMEWORKS/Sparkle.framework"
  mkdir -p "$FRAMEWORKS"
  # ditto preserves the framework's Versions/Current symlink layout.
  ditto "$ROOT/vendor/Sparkle/Sparkle.framework" "$SPARKLE_FW"
fi

echo "▸ Compiling app icon"
ACTOOL="$(xcrun -f actool 2>/dev/null || true)"
if [ -z "$ACTOOL" ] && [ -x "/Applications/Xcode.app/Contents/Developer/usr/bin/actool" ]; then
  ACTOOL="/Applications/Xcode.app/Contents/Developer/usr/bin/actool"
  export DEVELOPER_DIR="/Applications/Xcode.app/Contents/Developer"
fi
if [ -n "$ACTOOL" ] && [ -d "$ROOT/AppIcon.icon" ]; then
  ICON_OUT="$(mktemp -d)"
  if "$ACTOOL" "$ROOT/AppIcon.icon" --compile "$ICON_OUT" \
      --platform macosx --minimum-deployment-target 26.0 \
      --app-icon AppIcon \
      --output-partial-info-plist "$ICON_OUT/partial-info.plist" >/tmp/actool.log 2>&1; then
    [ -f "$ICON_OUT/Assets.car" ] && cp "$ICON_OUT/Assets.car" "$APP/Contents/Resources/"
    [ -f "$ICON_OUT/AppIcon.icns" ] && cp "$ICON_OUT/AppIcon.icns" "$APP/Contents/Resources/"
    echo "  (icon compiled from AppIcon.icon)"
  else
    echo "  WARNING: actool failed to compile AppIcon.icon — continuing without app icon (see /tmp/actool.log)"
  fi
  rm -rf "$ICON_OUT"
else
  echo "  WARNING: actool not found or AppIcon.icon missing — continuing without app icon"
fi

echo "▸ Code signing"

# The iCloud entitlements are *restricted*: macOS refuses to launch a binary that
# carries them unless the bundle embeds a provisioning profile authorising them —
# a Developer ID build signed with them dies at spawn.
SPARKLE_NESTED=()
if [ "$APP_STORE_BUILD" = 1 ]; then
  ENTITLEMENTS="$ROOT/Lurent-appstore.entitlements"
  cp "$PROVISION_PROFILE" "$APP/Contents/embedded.provisionprofile"
  echo "  embedded $(basename "$PROVISION_PROFILE") → sandboxed, iCloud container, no Sparkle"
else
  ENTITLEMENTS="$ROOT/Lurent.entitlements"
  SPARKLE_V="$SPARKLE_FW/Versions/Current"
  # Nested Sparkle executables/bundles, signed inside-out (deepest first) *before*
  # the framework and the app. Re-signing with *your* Developer ID is mandatory:
  # the app's hardened runtime enforces library validation, which only loads a
  # framework signed by the same team. They get no app entitlements (not sandboxed).
  SPARKLE_NESTED=(
    "$SPARKLE_V/XPCServices/Downloader.xpc"
    "$SPARKLE_V/XPCServices/Installer.xpc"
    "$SPARKLE_V/Autoupdate"
    "$SPARKLE_V/Updater.app"
  )
fi

# codesign with the hardened runtime; retry without a secure timestamp when the
# Apple timestamp server is unreachable (offline). Only a timestamped build can
# be notarized. Args: <identity> <entitlements-or-empty> <path>
sign_hardened() {
  local id="$1" ent="$2" path="$3"
  local args=(--force --options runtime --sign "$id")
  if [ -n "$ent" ]; then args+=(--entitlements "$ent"); fi
  if codesign "${args[@]}" --timestamp "$path" 2>/dev/null; then return 0; fi
  # Retry without a secure timestamp. The usual cause is an unreachable timestamp
  # server (offline), but any codesign failure lands here; if the real problem is
  # something else, this second attempt surfaces its error (stderr not silenced).
  echo "  ⚠ signing $(basename "$path") with a secure timestamp failed (offline?) — retrying without one"
  codesign "${args[@]}" --timestamp=none "$path"
}

# SIGN_IDENTITY controls how the bundle is signed:
#   unset / "auto" → auto-detect a "Developer ID Application" identity
#   "Developer ID Application: …" or a cert SHA-1 → sign with that identity
#   "-" → force ad-hoc (local use only)
# A Developer ID signature adds the hardened runtime + entitlements + a secure
# timestamp, so the result is ready for `./notarize.sh`. Ad-hoc runs locally but
# is rejected by Gatekeeper once downloaded.
SIGN_IDENTITY="${SIGN_IDENTITY-auto}"
if [ "$SIGN_IDENTITY" = "auto" ]; then
  # Capture first, then parse: `security … | awk …exit` can SIGPIPE-fail security
  # under `set -o pipefail` (the hazard notarize.sh/release.sh already avoid).
  IDENTITIES="$(security find-identity -v -p codesigning || true)"
  # A provisioned build has to be signed by the identity the profile was issued
  # for; Developer ID and a Development profile don't match.
  if [ -n "$PROVISION_PROFILE" ]; then
    SIGN_IDENTITY="$(awk -F'"' '/Apple Development/ {print $2; exit}' <<<"$IDENTITIES")"
    [ -n "$SIGN_IDENTITY" ] || { echo "  ✗ no \"Apple Development\" identity in the keychain"; exit 1; }
  else
    SIGN_IDENTITY="$(awk -F'"' '/Developer ID Application/ {print $2; exit}' <<<"$IDENTITIES")"
  fi
fi
if [ -n "$SIGN_IDENTITY" ] && [ "$SIGN_IDENTITY" != "-" ]; then
  if [ -n "$SPARKLE_FW" ]; then
    echo "  signing Sparkle.framework inside-out with $SIGN_IDENTITY"
    for c in "${SPARKLE_NESTED[@]}"; do sign_hardened "$SIGN_IDENTITY" "" "$c"; done
    sign_hardened "$SIGN_IDENTITY" "" "$SPARKLE_FW"
  fi
  echo "  signing Lurent.app"
  sign_hardened "$SIGN_IDENTITY" "$ENTITLEMENTS" "$APP"
  echo "  ✓ signed: $SIGN_IDENTITY (hardened runtime + entitlements)"
  echo "    → run ./notarize.sh to distribute (re-run online first if a timestamp was skipped)"
else
  echo "  ad-hoc signing (local use only)"
  for c in "${SPARKLE_NESTED[@]}"; do codesign --force --sign - "$c" >/dev/null 2>&1 || true; done
  [ -n "$SPARKLE_FW" ] && codesign --force --sign - "$SPARKLE_FW" >/dev/null 2>&1 || true
  codesign --force --sign - "$APP" >/dev/null 2>&1 || echo "  (codesign skipped)"
  echo "  ad-hoc signed — local use only (set SIGN_IDENTITY to a Developer ID to distribute)"
fi

echo "✓ Built: $APP"
echo "  Run with:  open \"$APP\""
